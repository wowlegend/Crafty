#!/usr/bin/env node
/**
 * READ ORDER — the orientation order, generated into CLAUDE.md so it has one home.
 *
 * Hand-kept copies of this order in three documents drifted apart, and a cold agent follows whichever it reads
 * first. The order lives here; doc-currency fails when the rendered block drifts, the same contract measure.mjs
 * and gate-table.mjs have. State a tool can print (HEAD, CI, PRs, worktrees, registry counts) is `npm run orient`,
 * the first entry, never prose.
 *
 *   node scripts/ci/read-order.mjs           print the canonical block
 *   node scripts/ci/read-order.mjs --write   write it into every surface
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../..');

export const BEGIN = '<!-- BEGIN READ-ORDER (regenerate: node frontend/scripts/ci/read-order.mjs --write) -->';
export const END = '<!-- END READ-ORDER -->';

/** Every surface that states the orientation order. Adding one here is all it takes. */
export const SURFACES = [
  'CLAUDE.md',
];

/** THE canonical order. Edit here, regenerate, never edit a rendered copy. */
export const ORDER = [
  { path: '`cd frontend && npm run orient`', note: 'HEAD, CI on main and on HEAD, the live Production sha, open PRs, unmerged worktrees, the cursor, registry counts. A main that is not green outranks every queue item.' },
  { path: '`memory/ACTIVE_PLAN.md`', note: 'the cursor: the live task table and the next step.' },
  { path: '`memory/registry.jsonl`', note: 'the one home for open work; how a row is written, laned and closed is `.claude/rules/registry.md`. Closed is final.' },
  { path: '`docs/superpowers/DECISIONS.md`', note: 'the decision record. A reversal is a new dated entry naming the one it supersedes.' },
  { path: '`memory/STATUS.md`', note: 'where the project stands; its §2 and G-ledger are the record the registry was harvested from.' },
  { path: '`docs/superpowers/INDEX.md`', note: 'the doc map: what to read, and which docs are history.' },
];

export function renderBlock() {
  return [
    BEGIN,
    '**Read in this order** (generated by `frontend/scripts/ci/read-order.mjs`; edit it there):',
    '',
    ...ORDER.map((o, i) => `${i + 1}. ${o.path} — ${o.note}`),
    END,
  ].join('\n');
}

/** Used by doc-currency: does this file carry the current block? */
export function checkFile(md) {
  const want = renderBlock();
  const i = md.indexOf(BEGIN);
  const j = md.indexOf(END);
  if (i < 0 || j < 0) return { ok: false, reason: 'READ-ORDER block missing' };
  return { ok: md.slice(i, j + END.length) === want, reason: 'READ-ORDER block is stale' };
}

export function checkAll() {
  return SURFACES.map((rel) => ({ rel, ...checkFile(readFileSync(join(ROOT, rel), 'utf8')) }));
}

function main() {
  if (!process.argv.includes('--write')) {
    console.log(renderBlock());
    const bad = checkAll().filter((r) => !r.ok);
    if (bad.length) {
      console.error(`\nread-order: ${bad.length} surface(s) stale: ${bad.map((b) => `${b.rel} (${b.reason})`).join(', ')}`);
      process.exit(1);
    }
    console.log(`\n✓ read-order: all ${SURFACES.length} surfaces current`);
    return;
  }
  const block = renderBlock();
  for (const rel of SURFACES) {
    const p = join(ROOT, rel);
    const md = readFileSync(p, 'utf8');
    const i = md.indexOf(BEGIN);
    const j = md.indexOf(END);
    if (i < 0 || j < 0) {
      console.error(`read-order: no markers in ${rel} — add ${BEGIN} / ${END} around its read-order list first`);
      process.exit(1);
    }
    writeFileSync(p, md.slice(0, i) + block + md.slice(j + END.length));
    console.log(`read-order: wrote ${rel}`);
  }
}

if (import.meta.main) main();
