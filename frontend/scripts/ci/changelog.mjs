#!/usr/bin/env node
/**
 * changelog.mjs — memory/CHANGELOG.md, generated from git and the merged pull requests, and checked against git.
 *
 * WHAT A LANDING IS HERE. A lane lands by fast-forward after merging main in (`CLAUDE.md` "Landing"), so main's
 * first-parent chain runs through the last lane's own commits and is not a list of landings, and git keeps no record
 * of where main pointed. Two things in the history do prove a landing:
 *   - a lane that took main in: `merge main ...`, `merge origin/main ...` or git's own "Merge remote-tracking branch
 *     'origin/main'" / "Merge branch 'main'". Its second parent is a commit main pointed at.
 *   - a merge into main on the first-parent chain, as the June milestones landed ("Merge S2-A-M1: ..."): a merge whose
 *     subject starts "Merge " and is not one of git's default lane-side messages. HEAD itself is never required (a
 *     commit cannot name itself), which is also what keeps GitHub's pull-request checkout ("Merge <sha> into <sha>",
 *     HEAD of every pull_request CI run) out.
 * Those are the REQUIRED lines. `--write` adds every merged pull request whose landed commit is in this history, with
 * GitHub's title and number (`gh pr list`), and a required landing that is a pull request's takes its line.
 *
 * One line per landing, newest first, under the UTC day of the landed commit's committer time:
 *   - <title> (#<pr>, <sha8>)      a pull request
 *   - <title> (<sha8>)             a landing git proves that no merged pull request names; the title is git's
 *
 * `--check` (offline; the commit tier and CI run it beside doc-currency) fails when:
 *   - a required landing is not listed (stale: main moved, a lane took it in, nobody ran `--write`);
 *   - a line names a commit that is not in this history, or an abbreviation that is ambiguous;
 *   - a git-derived line's title is not what git derives (a hand edit);
 *   - the file is not byte-identical to a render of its own lines (order, grouping, header, spacing);
 *   - the history holds no landing at all, or the clone is shallow: a check with nothing to compare reads as COULD NOT
 *     CHECK, never as a pass.
 * It does NOT check, and says so on its PASS line: a pull request's title or number against GitHub (the network); a
 * landing no later commit took in (the newest landing, two lanes that landed back to back, a direct push to main
 * nobody merged): git alone cannot see that main pointed there; the commits inside a landing (only its tip is named).
 *
 *   node scripts/ci/changelog.mjs --write          regenerate (needs `gh` for the pull requests)
 *   node scripts/ci/changelog.mjs --check          exit 1 on any of the above
 *   node scripts/ci/changelog.mjs --check --root=<dir>   another repository (a test seam)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const TARGET = 'memory/CHANGELOG.md';

/** A lane taking main in: the merge's second parent is a commit main pointed at. */
const LANE_MERGE = /^(?:merge (?:origin\/)?main\b|Merge (?:remote-tracking )?branch '(?:origin\/)?main')/;
/** A merge into main as the June milestones landed; never git's default lane-side message. */
const MILESTONE_MERGE = /^Merge (?!(?:remote-tracking )?branch ')/;

const HEADER = `# Changelog

Generated by \`node frontend/scripts/ci/changelog.mjs --write\`; do not edit it by hand (\`--check\` runs on every
commit and in CI). One line per landing on main, newest first, under the UTC day of the landed commit: a pull
request's title and number, or the subject of a landing git can prove that no pull request names. A landing is listed
once a later change takes main in, so the newest one can be missing here until the next.

Before 2026-10-28 lanes did not land through pull requests: the merges into main in June are listed, the direct
commits of July to October are in \`git log\`, and the hand-written history to 2026-10-29 is
\`git show records/2026-10-29:memory/CHANGELOG.md\`.
`;

const LINE_RE = /^- (.+) \((?:#(\d+), )?([0-9a-f]{8})\)$/;

/** process.env with every GIT_* removed, so git reads the repository at `root`, never an inherited GIT_DIR's. */
const scrubbedEnv = () => Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('GIT_')));
const git = (root, args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', env: scrubbedEnv(), maxBuffer: 1 << 28 });

/** The title git gives a landing: a milestone merge loses its "Merge " prefix, anything else is its subject. */
function gitTitle(c) {
  return c.parents.length > 1 && MILESTONE_MERGE.test(c.subject)
    ? c.subject.replace(/^Merge:?\s+/, '')
    : c.subject;
}

/**
 * Read the history at `ref`: every commit reachable from it, and the landings it proves.
 * @returns {{head: string, commits: Map<string, {sha, parents, ct, subject}>, required: {sha, title, via}[]}}
 */
export function collect({ root = ROOT, ref = 'HEAD' } = {}) {
  if (git(root, ['rev-parse', '--is-shallow-repository']).trim() === 'true') {
    throw new Error('this clone is shallow, so its history cannot show the landings');
  }
  const head = git(root, ['rev-parse', ref]).trim();
  const commits = new Map();
  for (const rec of git(root, ['log', '--format=%H%x1f%P%x1f%ct%x1f%s%x1e', ref]).split('\x1e')) {
    const [sha, parents, ct, subject] = rec.replace(/^\n/, '').split('\x1f');
    if (!sha) continue;
    commits.set(sha, { sha, parents: parents ? parents.split(' ') : [], ct: Number(ct), subject: subject ?? '' });
  }
  const firstParent = new Set(git(root, ['rev-list', '--first-parent', ref]).split('\n').filter(Boolean));
  const required = new Map();
  for (const c of commits.values()) {
    if (c.parents.length < 2) continue;
    if (LANE_MERGE.test(c.subject)) {
      const tip = c.parents[1];
      if (tip !== head && commits.has(tip) && !required.has(tip)) required.set(tip, { sha: tip, title: gitTitle(commits.get(tip)), via: c.sha });
    } else if (c.sha !== head && firstParent.has(c.sha) && MILESTONE_MERGE.test(c.subject)) {
      if (!required.has(c.sha)) required.set(c.sha, { sha: c.sha, title: gitTitle(c), via: c.sha });
    }
  }
  return { head, commits, required: [...required.values()] };
}

/** PURE. Entries `{sha, title, pr, ct}` -> the file: newest first, grouped by UTC day. */
export function render(entries) {
  const sorted = [...entries].sort((a, b) => b.ct - a.ct || (a.sha < b.sha ? -1 : a.sha > b.sha ? 1 : 0));
  const days = new Map();
  for (const e of sorted) {
    const day = new Date(e.ct * 1000).toISOString().slice(0, 10);
    if (!days.has(day)) days.set(day, []);
    days.get(day).push(`- ${e.title} (${e.pr ? `#${e.pr}, ` : ''}${e.sha.slice(0, 8)})`);
  }
  const blocks = [...days].map(([day, lines]) => `## ${day}\n\n${lines.map((l) => `${l}\n`).join('')}`);
  return blocks.length ? `${HEADER}\n${blocks.join('\n')}` : HEADER;
}

/** PURE. The file -> its entry lines, and the line numbers of `- ` lines that are not entries. */
function parse(text) {
  const entries = [];
  const bad = [];
  text.split('\n').forEach((line, i) => {
    if (!line.startsWith('- ')) return;
    const m = line.match(LINE_RE);
    if (!m) bad.push(i + 1);
    else entries.push({ lineNo: i + 1, title: m[1], pr: m[2] ? Number(m[2]) : null, abbrev: m[3] });
  });
  return { entries, bad };
}

/**
 * Check the file at `root` against the history at `ref`. Never prints or exits.
 * @returns {{errors: string[], checked: {lines: number, required: number}}}
 */
export function check({ root = ROOT, ref = 'HEAD' } = {}) {
  const errors = [];
  const checked = { lines: 0, required: 0 };
  let hist;
  try {
    hist = collect({ root, ref });
  } catch (e) {
    return { errors: [`COULD NOT CHECK: ${e.message}`], checked };
  }
  checked.required = hist.required.length;
  if (hist.required.length === 0) {
    errors.push('COULD NOT CHECK: this history holds no landing (no merge into main, no lane that took main in)');
  }
  const abs = join(root, TARGET);
  if (!existsSync(abs)) return { errors: [...errors, `${TARGET} does not exist`], checked };
  const text = readFileSync(abs, 'utf8');
  const { entries, bad } = parse(text);
  checked.lines = entries.length;
  if (bad.length) {
    errors.push(`${bad.length} line(s) are not changelog entries (first at line ${bad.slice(0, 5).join(', ')})`);
  }
  const byPrefix = new Map();
  for (const sha of hist.commits.keys()) {
    const k = sha.slice(0, 8);
    byPrefix.set(k, [...(byPrefix.get(k) || []), sha]);
  }
  const resolved = [];
  for (const e of entries) {
    const hits = byPrefix.get(e.abbrev) || [];
    if (hits.length !== 1) {
      errors.push(`line ${e.lineNo} names ${e.abbrev}, which is ${hits.length ? 'ambiguous' : 'not in this history'}`);
      continue;
    }
    const c = hist.commits.get(hits[0]);
    if (e.pr === null && e.title !== gitTitle(c)) {
      errors.push(`line ${e.lineNo} reads "${e.title}", but its commit says "${gitTitle(c)}"`);
    }
    resolved.push({ sha: c.sha, title: e.title, pr: e.pr, ct: c.ct });
  }
  const listed = new Set(resolved.map((e) => e.sha));
  for (const r of hist.required) {
    if (!listed.has(r.sha)) {
      errors.push(`${r.sha.slice(0, 8)} "${r.title}" reached main (taken in by ${r.via.slice(0, 8)}) and is not listed`);
    }
  }
  if (resolved.length === entries.length && !bad.length && render(resolved) !== text) {
    errors.push('the file is not in generated form: its order, day grouping, header or spacing differs from a render of its own lines');
  }
  return { errors, checked };
}

/**
 * Regenerate the file at `root` from the history at `ref` and the merged pull requests `prs`
 * (`{number, title, landed}`, `landed` a sha or a list of candidate shas; the first one in this history counts).
 */
export function write({ root = ROOT, ref = 'HEAD', prs = [] } = {}) {
  const hist = collect({ root, ref });
  const lines = new Map(hist.required.map((r) => [r.sha, { sha: r.sha, title: r.title, pr: null }]));
  let fromPrs = 0;
  for (const p of prs) {
    const sha = [p.landed].flat().find((s) => s && hist.commits.has(s));
    if (!sha) continue;
    fromPrs += 1;
    lines.set(sha, { sha, title: String(p.title).replace(/\s+/g, ' ').trim(), pr: p.number });
  }
  const text = render([...lines.values()].map((e) => ({ ...e, ct: hist.commits.get(e.sha).ct })));
  writeFileSync(join(root, TARGET), text);
  return { lines: lines.size, fromPrs, required: hist.required.length };
}

/** The merged pull requests, from GitHub. */
function mergedPrs(root) {
  const out = execFileSync(
    'gh',
    ['pr', 'list', '--state', 'merged', '--base', 'main', '--limit', '1000', '--json', 'number,title,headRefOid,mergeCommit'],
    { cwd: root, encoding: 'utf8', env: scrubbedEnv() },
  );
  return JSON.parse(out).map((p) => ({ number: p.number, title: p.title, landed: [p.mergeCommit?.oid, p.headRefOid] }));
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const rootArg = args.find((a) => a.startsWith('--root='));
  const root = rootArg ? resolve(rootArg.slice('--root='.length)) : ROOT;
  if (args.includes('--write')) {
    let prs;
    try {
      prs = mergedPrs(root);
    } catch (e) {
      console.error(`✖ changelog: COULD NOT FETCH the merged pull requests (gh pr list): ${e.message.split('\n')[0]}; nothing written`);
      process.exit(2);
    }
    const r = write({ root, prs });
    console.log(`✓ changelog: wrote ${TARGET}: ${r.lines} lines, ${r.fromPrs} from pull requests, ${r.required} landings git proves`);
  } else if (args.includes('--check')) {
    const { errors, checked } = check({ root });
    if (errors.length) {
      console.error(`✖ changelog: ${TARGET} is stale, hand-edited or names a commit outside this history (${errors.length} issue(s)):`);
      for (const e of errors.slice(0, 20)) console.error(`  • ${e}`);
      if (errors.length > 20) console.error(`  … and ${errors.length - 20} more`);
      console.error('Regenerate: node frontend/scripts/ci/changelog.mjs --write (after taking main in; gh supplies the pull request titles).');
      process.exit(1);
    }
    console.log(
      `✓ changelog: ${checked.lines} lines, ${checked.required} required landings found in this history and listed ` +
        '(not checked: pull request titles and numbers, which GitHub holds, and a landing no later commit took in)',
    );
  } else {
    console.error('usage: node scripts/ci/changelog.mjs --write | --check [--root=<dir>]');
    process.exit(2);
  }
}
